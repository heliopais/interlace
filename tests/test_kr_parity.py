"""Parity tests: KR variance-covariance derivatives vs R's pbkrtest/lmerTest.

Compares interlace model parameters against R lme4 on the same data, then
verifies our KR derivatives produce a bias correction consistent with R's
vcovAdj output.

Reference values generated by: Rscript tests/fixtures/gen_kr_parity.R
Requires: lme4, pbkrtest, lmerTest, jsonlite
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import interlace
from interlace.kr_vcov import kr_vcov_derivs

FIXTURES = Path(__file__).parent / "fixtures"


def _load_fixture(name: str) -> dict:
    with open(FIXTURES / name) as f:
        return json.load(f)


# ---------------------------------------------------------------------------
# One-factor model: y ~ x + (1 | group)
# ---------------------------------------------------------------------------


@pytest.fixture(scope="module")
def one_factor():
    """Load R fixture and fit the same model in interlace."""
    ref = _load_fixture("kr_parity_one_factor.json")
    df = pd.DataFrame(
        {
            "y": np.array(ref["y"]),
            "x": np.array(ref["x"]),
            "group": [str(g) for g in ref["group"]],
        }
    )
    result = interlace.fit("y ~ x", data=df, groups="group")
    return ref, result


class TestOneFactorModelParity:
    """Verify interlace model matches R lme4 on the same data."""

    def test_theta_matches_r(self, one_factor):
        ref, result = one_factor
        r_theta = list(ref["theta"].values())
        np.testing.assert_allclose(result.theta, r_theta, rtol=0.01)

    def test_beta_matches_r(self, one_factor):
        ref, result = one_factor
        r_beta = list(ref["beta"].values())
        np.testing.assert_allclose(np.array(result.fe_params), r_beta, atol=1e-3)

    def test_sigma_matches_r(self, one_factor):
        ref, result = one_factor
        np.testing.assert_allclose(np.sqrt(result.scale), ref["sigma"], rtol=0.01)

    def test_fe_cov_matches_r(self, one_factor):
        ref, result = one_factor
        r_fe_cov = np.array(ref["fe_cov"])
        np.testing.assert_allclose(result.fe_cov, r_fe_cov, rtol=0.01)


class TestOneFactorKRDerivatives:
    """Validate KR derivatives against R's vcovAdj output."""

    def test_kr_bias_correction_direction(self, one_factor):
        """The simple bias correction should move fe_cov toward R's vcovAdj."""
        ref, result = one_factor
        kr = kr_vcov_derivs(result)

        # R's KR correction
        r_kr_adj = np.array(ref["kr_vcov_adj"])
        r_correction = r_kr_adj - np.array(ref["fe_cov"])

        # Our simple second-order bias correction: 0.5 * sum_ij Phi_ij * d2C_ij
        k = len(result.theta)
        bias_correction = np.zeros_like(kr.fe_cov)
        for i in range(k):
            for j in range(k):
                bias_correction += 0.5 * kr.Phi[i, j] * kr.d2C[i, j]

        # The corrections should have the same sign on the diagonal
        # (KR typically inflates variance estimates)
        r_diag = np.diag(r_correction)
        our_diag = np.diag(bias_correction)
        # At least the sign should agree for the majority of entries
        nonzero = np.abs(r_diag) > 1e-10
        if np.any(nonzero):
            sign_agreement = np.sign(r_diag[nonzero]) == np.sign(our_diag[nonzero])
            assert np.mean(sign_agreement) >= 0.5, (
                f"Bias correction signs disagree: R={r_diag}, ours={our_diag}"
            )

    def test_kr_correction_magnitude_reasonable(self, one_factor):
        """The bias correction should be small relative to fe_cov."""
        ref, result = one_factor
        kr = kr_vcov_derivs(result)

        k = len(result.theta)
        bias_correction = np.zeros_like(kr.fe_cov)
        for i in range(k):
            for j in range(k):
                bias_correction += 0.5 * kr.Phi[i, j] * kr.d2C[i, j]

        # The correction should be < 50% of fe_cov diagonal
        ratio = np.abs(np.diag(bias_correction)) / np.abs(np.diag(kr.fe_cov))
        assert np.all(ratio < 0.5), (
            f"Bias correction too large relative to fe_cov: ratio={ratio}"
        )


