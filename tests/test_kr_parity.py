class TestTwoFactorKRDerivatives:
    """Validate KR derivatives against R's vcovAdj for the crossed model."""

    def test_kr_derivatives_finite(self, two_factor):
        _, result = two_factor
        kr = kr_vcov_derivs(result)
        assert np.all(np.isfinite(kr.dC))
        assert np.all(np.isfinite(kr.d2C))
        assert np.all(np.isfinite(kr.Phi))

    def test_kr_correction_same_sign_as_r(self, two_factor):
        """The KR diagonal correction should agree in sign with R's vcovAdj."""
        ref, result = two_factor
        kr = kr_vcov_derivs(result)

        r_kr_adj = np.array(ref["kr_vcov_adj"])
        r_correction_diag = np.diag(r_kr_adj) - np.diag(np.array(ref["fe_cov"]))

        k = len(result.theta)
        bias_correction = np.zeros_like(kr.fe_cov)
        for i in range(k):
            for j in range(k):
                bias_correction += 0.5 * kr.Phi[i, j] * kr.d2C[i, j]

        our_correction_diag = np.diag(bias_correction)

        # For entries where R's correction is non-negligible, signs should agree
        nonzero = np.abs(r_correction_diag) > 1e-10
        if np.any(nonzero):
            sign_ok = np.sign(r_correction_diag[nonzero]) == np.sign(
                our_correction_diag[nonzero]
            )
            assert np.mean(sign_ok) >= 0.5, (
                f"Sign mismatch: R correction={r_correction_diag}, "
                f"ours={our_correction_diag}"
            )

    def test_r_kr_reference_stored(self, two_factor):
        """Verify R's kr_vcov_adj and kr_dfs are stored for downstream use.

        The full KR formula (C_KR = C + 2*Lambda) requires V-derivatives in
        the original variance-component parameterisation, not the profiled
        theta parameterisation that our C-derivatives use.  The downstream
        task (interlace-sbo) will implement the correct mapping and validate
        against these R reference values.
        """
        ref, _ = two_factor
        r_kr_adj = np.array(ref["kr_vcov_adj"])
        r_kr_dfs = ref["kr_dfs"]
        # Just verify the reference data is present and well-formed
        assert r_kr_adj.shape == (2, 2)
        assert len(r_kr_dfs) == 2
        assert all(v > 0 for v in r_kr_dfs.values())
