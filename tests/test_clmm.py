# ---- API and edge-case tests ----


class TestCLMMAPI:
    """Basic API contract tests for interlace.clmm()."""

    def test_result_has_expected_attributes(self, wine_data: pd.DataFrame) -> None:
        result = interlace.clmm("rating ~ temp + contact", wine_data, groups="judge")
        assert hasattr(result, "thresholds")
        assert hasattr(result, "threshold_bse")
        assert hasattr(result, "fe_params")
        assert hasattr(result, "fe_bse")
        assert hasattr(result, "random_effects")
        assert hasattr(result, "variance_components")
        assert hasattr(result, "llf")
        assert hasattr(result, "aic")
        assert hasattr(result, "bic")
        assert hasattr(result, "converged")
        assert hasattr(result, "nobs")

    def test_threshold_ordering(self, wine_data: pd.DataFrame) -> None:
        """Thresholds must be strictly increasing."""
        result = interlace.clmm("rating ~ temp + contact", wine_data, groups="judge")
        vals = list(result.thresholds.values())
        for i in range(1, len(vals)):
            assert vals[i] > vals[i - 1], f"Thresholds not increasing: {vals}"

    def test_cloglog_link_runs(self, wine_data: pd.DataFrame) -> None:
        """cloglog link should run without error."""
        result = interlace.clmm(
            "rating ~ temp + contact",
            wine_data,
            groups="judge",
            link="cloglog",
        )
        assert result.converged

    def test_bad_link_raises(self, wine_data: pd.DataFrame) -> None:
        with pytest.raises(ValueError, match="link"):
            interlace.clmm(
                "rating ~ temp + contact",
                wine_data,
                groups="judge",
                link="identity",
            )
