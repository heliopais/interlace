"""Tests for Kenward-Roger adjusted covariance and denominator DFs.

Validates interlace's KR implementation against R's pbkrtest::vcovAdj()
and lmerTest::summary(ddf="Kenward-Roger").

Reference values generated by: Rscript tests/fixtures/gen_kr_parity.R
Requires: lme4, pbkrtest, lmerTest, jsonlite
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import interlace
from interlace.kenward_roger import kenward_roger

FIXTURES = Path(__file__).parent / "fixtures"


def _load_fixture(name: str) -> dict:
    with open(FIXTURES / name) as f:
        return json.load(f)


# ---------------------------------------------------------------------------
# One-factor model: y ~ x + (1 | group)
# ---------------------------------------------------------------------------


@pytest.fixture(scope="module")
def one_factor():
    """Load R fixture and fit the same model in interlace."""
    ref = _load_fixture("kr_parity_one_factor.json")
    df = pd.DataFrame(
        {
            "y": np.array(ref["y"]),
            "x": np.array(ref["x"]),
            "group": [str(g) for g in ref["group"]],
        }
    )
    result = interlace.fit("y ~ x", data=df, groups="group")
    return ref, result


class TestOneFactorKR:
    """KR parity: y ~ x + (1 | group), 15 groups x 8 obs."""

    def test_kr_vcov_adj_matches_r(self, one_factor):
        """KR-adjusted FE covariance should match R's vcovAdj()."""
        ref, result = one_factor
        r_kr_adj = np.array(ref["kr_vcov_adj"])
        C_adj, _ = kenward_roger(result)
        np.testing.assert_allclose(C_adj, r_kr_adj, rtol=0.01)

    def test_kr_dfs_intercept_matches_r(self, one_factor):
        """KR DF for intercept should match R's lmerTest."""
        ref, result = one_factor
        r_df_intercept = ref["kr_dfs"]["(Intercept)"]
        _, dfs = kenward_roger(result)
        np.testing.assert_allclose(dfs[0], r_df_intercept, rtol=0.01)

    def test_kr_dfs_slope_matches_r(self, one_factor):
        """KR DF for slope should match R's lmerTest."""
        ref, result = one_factor
        r_df_x = ref["kr_dfs"]["x"]
        _, dfs = kenward_roger(result)
        np.testing.assert_allclose(dfs[1], r_df_x, rtol=0.01)


