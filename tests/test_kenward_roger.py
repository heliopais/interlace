# ---------------------------------------------------------------------------
# Properties: KR adjustments should have expected characteristics
# ---------------------------------------------------------------------------


class TestKRProperties:
    """Test structural properties of the KR adjustment."""

    def test_c_adj_symmetric(self, one_factor):
        _, result = one_factor
        C_adj, _ = kenward_roger(result)
        np.testing.assert_allclose(C_adj, C_adj.T, atol=1e-12)

    def test_c_adj_positive_diagonal(self, one_factor):
        _, result = one_factor
        C_adj, _ = kenward_roger(result)
        assert np.all(np.diag(C_adj) > 0)

    def test_dfs_positive(self, one_factor):
        _, result = one_factor
        _, dfs = kenward_roger(result)
        assert np.all(dfs >= 1.0)

    def test_kr_dfs_finite(self, two_factor):
        _, result = two_factor
        _, dfs = kenward_roger(result)
        assert np.all(np.isfinite(dfs))

    def test_kr_dfs_differ_from_satterthwaite(self, one_factor):
        """KR DFs should differ from Satterthwaite for the slope coefficient.

        The slope's variance depends heavily on σ²_resid, which is profiled
        out in Satterthwaite but treated as a free parameter in KR.  This
        gives a substantially lower (more conservative) DF.
        """
        from interlace.satterthwaite import satterthwaite_dfs

        _, result = one_factor
        _, kr_dfs = kenward_roger(result)
        satt_dfs = satterthwaite_dfs(result)

        # For the slope coefficient, KR should give a much smaller DF
        # (profiled Satterthwaite overestimates slope DF by ~8x)
        assert kr_dfs[1] < satt_dfs[1] * 0.5
